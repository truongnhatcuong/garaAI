import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdir, mkdtemp, readFile, readdir, rename, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ffmpegPath from "ffmpeg-static";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = path.resolve(root, process.argv[3] ?? "public/videos/ea837389c2bb4f5881f39137fffa733f.mp4");
const outputDir = path.join(root, "public/frames/autocare");
const manifestPath = path.join(root, "src/generated/autocare-scroll-frames.ts");
const width = Number(process.argv[2] ?? 2560);
const frameRate = 24;
const quality = 90;

if (!ffmpegPath || !Number.isInteger(width) || width < 1920 || width > 3840 || width % 2 !== 0) {
  throw new Error("Cần FFmpeg và chiều rộng chẵn từ 1920 đến 3840. Ví dụ: npm run video:frames -- 3840 public/videos/video-4k.mp4");
}

const probe = spawnSync(ffmpegPath, ["-hide_banner", "-i", source], { encoding: "utf8" });
const sourceSize = probe.stderr.match(/Video:.*?\s(\d{3,5})x(\d{3,5})[,\s]/);
if (!sourceSize) throw new Error(`Không đọc được kích thước video: ${probe.stderr}`);
const sourceWidth = Number(sourceSize[1]);
const sourceHeight = Number(sourceSize[2]);
const height = Math.round((width * sourceHeight / sourceWidth) / 2) * 2;
const mobileWidth = Math.min(sourceWidth, 1280);
const mobileHeight = Math.round((mobileWidth * sourceHeight / sourceWidth) / 2) * 2;
const version = createHash("sha256").update(await readFile(source)).update(`${width}:${frameRate}:${quality}`).digest("hex").slice(0, 12);

if (sourceWidth < 1920 || sourceHeight < 1080) {
  process.stderr.write(`Lưu ý: nguồn chỉ ${sourceWidth}×${sourceHeight}; nâng kích thước frame không bổ sung chi tiết Full HD/4K thật.\n`);
}

await mkdir(path.dirname(outputDir), { recursive: true });
const staging = await mkdtemp(path.join(path.dirname(outputDir), ".autocare-build-"));
await mkdir(path.join(staging, "mobile"));

try {
  const result = spawnSync(ffmpegPath, [
    "-y", "-hide_banner", "-loglevel", "error", "-i", source,
    "-filter_complex", `[0:v]fps=${frameRate},split=2[desktop][mobile];[desktop]scale=${width}:${height}:flags=lanczos[d];[mobile]scale=${mobileWidth}:${mobileHeight}:flags=lanczos[m]`,
    "-map", "[d]", "-an", "-c:v", "libwebp", "-quality", String(quality), "-compression_level", "6",
    "-start_number", "1", path.join(staging, "frame_%04d.webp"),
    "-map", "[m]", "-an", "-c:v", "libwebp", "-quality", String(quality), "-compression_level", "6",
    "-start_number", "1", path.join(staging, "mobile/frame_%04d.webp"),
  ], { stdio: "inherit" });
  if (result.status !== 0) throw new Error(`FFmpeg thoát với mã ${result.status}`);

  const files = (await readdir(staging)).filter((name) => /^frame_\d{4}\.webp$/.test(name)).sort();
  const mobileFiles = (await readdir(path.join(staging, "mobile"))).filter((name) => /^frame_\d{4}\.webp$/.test(name)).sort();
  const frameCount = files.length;
  if (frameCount < 2 || files.some((name, index) => name !== `frame_${String(index + 1).padStart(4, "0")}.webp`) || files.join() !== mobileFiles.join()) {
    throw new Error("Chuỗi frame không đầy đủ hoặc không khớp giữa desktop và mobile.");
  }

  // Replace only this generated sequence after both new variants are complete.
  await rm(outputDir, { recursive: true, force: true });
  await rename(staging, outputDir);
  await writeFile(manifestPath, `// Generated by scripts/generate-scroll-frames.mjs.\nexport const autocareScrollFrames = {\n  count: ${frameCount},\n  width: ${width},\n  height: ${height},\n  mobileWidth: ${mobileWidth},\n  mobileHeight: ${mobileHeight},\n  sourceWidth: ${sourceWidth},\n  sourceHeight: ${sourceHeight},\n  version: "${version}",\n  path: "/frames/autocare/frame_",\n  mobilePath: "/frames/autocare/mobile/frame_",\n} as const;\n`);
  process.stdout.write(`Đã thay frame cũ bằng ${frameCount} frame desktop ${width}×${height} và mobile ${mobileWidth}×${mobileHeight}.\n`);
} finally {
  await rm(staging, { recursive: true, force: true });
}
